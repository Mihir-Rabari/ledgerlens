"""FastAPI service: the LedgerLens console API + static demo UI.

Also hosts two demo-only mechanics:
- a live alert feed (optional, LIVE_FEED=1): new synthetic alerts arrive while
  the console is open, showing ingestion + the queue responding in real time;
- a stress bench endpoint that runs parallel investigations across tenants.
"""

from __future__ import annotations

import asyncio
import os
import time
from concurrent.futures import ThreadPoolExecutor
from datetime import UTC, datetime
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse, PlainTextResponse
from pydantic import BaseModel

from .agents import AgentError, ask_question, investigate_alert
from .config import CONFIG
from .graph import connection
from .tools import run_tool, tool_catalog

STATIC_DIR = Path(__file__).parent.parent / "static"

LIVE_FEED = os.environ.get("LIVE_FEED", "") == "1"
FEED_TEMPLATES = [
    ("new_beneficiary_high_value", 2, "New beneficiary flagged: {acct} received {amt} from a fresh counterparty."),
    ("device_hopping", 3, "Account {acct} seen on {n} new devices across two countries this week."),
    ("rapid_velocity", 3, "{n} rapid outbound transfers within one hour on {acct}."),
    ("new_beneficiary_high_value", 2, "Beneficiary {acct} received a cross-border transfer of {amt}."),
]


class InvestigateRequest(BaseModel):
    alert_id: str


class AskRequest(BaseModel):
    message: str
    session_id: str | None = None


def _now() -> str:
    return datetime.now(UTC).isoformat(timespec="seconds")


def build_report(conn, tenant: str, case_id: str) -> str:
    """Evidence-cited case report, derived entirely from graph state."""
    case = run_tool(conn, tenant, "get_case", {"case_id": case_id})
    if not case["ok"]:
        raise HTTPException(status_code=404, detail=case["error"]["detail"])
    d = case["data"]
    sessions = run_tool(conn, tenant, "list_sessions", {})["data"]["sessions"]

    def fmt_ts(ts: str) -> str:
        return (ts or "").replace("T", " ").split("+")[0]

    lines = [
        f"# Case report — {d['id']}",
        "",
        f"**{d['title']}**",
        "",
        f"- Status: **{d['status']}** · severity {d['severity']}",
        f"- Opened: {fmt_ts(d['opened_at'])}" + (f" · Closed: {fmt_ts(d['closed_at'])}" if d.get("closed_at") else ""),
        f"- Tenant: `{tenant}` (isolated graph `bank_{tenant}`)",
        "",
        "## Outcome",
        "",
        d.get("outcome") or "_not closed yet_",
        "",
        "## Alerts investigated",
        "",
    ]
    lines += [f"- `{a}`" for a in d.get("alerts") or []] or ["- _none_"]
    lines += ["", "## Accounts involved", ""]
    lines += [f"- `{a}`" for a in d.get("accounts") or []] or ["- _none_"]
    lines += ["", "## Findings (semantic memory, persisted for future sessions)", ""]
    for f in d.get("findings") or []:
        lines.append(f"- ({f.get('confidence', '—')}) {f.get('text')} — _learned {fmt_ts(f.get('at', ''))}_")
    if not d.get("findings"):
        lines.append("- _none recorded_")
    lines += ["", "## Actions (audited)", ""]
    for a in d.get("actions") or []:
        lines.append(f"- **{a.get('kind')}** by {a.get('by')} at {fmt_ts(a.get('at', ''))} — {a.get('reason')}")
    if not d.get("actions"):
        lines.append("- _none recorded_")
    lines += ["", "## Sessions", ""]
    lines += [f"- `{s['id']}` — {s['agent']} at {fmt_ts(s.get('started_at', ''))}"
              + (f" (handoff from `{s['handed_from'][0]}`)" if s.get("handed_from") else "")
              + (f", {s['findings']} finding(s), {s['messages']} message(s)"
                 if any(ss["id"] == s["id"] for ss in sessions) else "")
              for s in sessions[:8]]
    lines += ["", "---", "_Generated by LedgerLens from the case subgraph; every claim above is a node or edge in FalkorDB._"]
    return "\n".join(lines)


def create_app() -> FastAPI:
    app = FastAPI(title="LedgerLens", version="0.1.0")
    conn = connection()
    feed_state = {"counter": 0}

    @app.get("/healthz")
    def healthz() -> dict:
        try:
            tenants = conn.list_tenants()
            falkordb_ok = True
        except Exception:
            tenants, falkordb_ok = [], False
        return {"ok": falkordb_ok, "tenants": tenants,
                "llm_configured": CONFIG.llm_ready, "live_feed": LIVE_FEED}

    @app.get("/api/tenants")
    def tenants() -> dict:
        return {"tenants": conn.list_tenants()}

    @app.get("/api/tenants/{tenant}/stats")
    def stats(tenant: str) -> dict:
        return run_tool(conn, tenant, "graph_stats", {})

    @app.get("/api/tenants/{tenant}/alerts")
    def alerts(tenant: str, status: str = "open") -> dict:
        return run_tool(conn, tenant, "list_alerts", {"status": status})

    @app.get("/api/tenants/{tenant}/cases")
    def cases(tenant: str, status: str = "all") -> dict:
        return run_tool(conn, tenant, "list_cases", {"status": status})

    @app.get("/api/tenants/{tenant}/case/{case_id}")
    def case(tenant: str, case_id: str) -> dict:
        return run_tool(conn, tenant, "get_case", {"case_id": case_id})

    @app.get("/api/tenants/{tenant}/case/{case_id}/report")
    def case_report(tenant: str, case_id: str) -> PlainTextResponse:
        return PlainTextResponse(build_report(conn, tenant, case_id),
                                 media_type="text/markdown; charset=utf-8")

    @app.get("/api/tenants/{tenant}/sessions")
    def sessions(tenant: str) -> dict:
        return run_tool(conn, tenant, "list_sessions", {})

    @app.get("/api/tenants/{tenant}/graph")
    def graph(tenant: str, ids: str) -> dict:
        return run_tool(conn, tenant, "component_graph", {"member_ids": [i for i in ids.split(",") if i]})

    @app.get("/api/tools")
    def tools() -> dict:
        return {"tools": tool_catalog()}

    @app.post("/api/tenants/{tenant}/investigate")
    def investigate(tenant: str, req: InvestigateRequest) -> dict:
        try:
            result = investigate_alert(conn, tenant, req.alert_id)
        except AgentError as exc:
            raise HTTPException(status_code=503, detail=str(exc)) from exc
        return {
            "tenant": result.tenant,
            "alert_id": result.alert_id,
            "handoff": result.handoff,
            "case_id": result.case_id,
            "analyst_session_id": result.analyst_session_id,
            "investigator_session_id": result.investigator_session_id,
            "analyst_final": result.analyst_final,
            "investigator_final": result.investigator_final,
            "turns": [vars(t) for t in result.turns],
        }

    @app.post("/api/tenants/{tenant}/ask")
    def ask(tenant: str, req: AskRequest) -> dict:
        try:
            return ask_question(conn, tenant, req.message, req.session_id)
        except AgentError as exc:
            raise HTTPException(status_code=503, detail=str(exc)) from exc

    @app.post("/api/bench")
    def bench() -> dict:
        """Run parallel investigations across tenants — the concurrency demo."""
        if not CONFIG.llm_ready:
            raise HTTPException(status_code=503, detail="LLM endpoint not configured")
        jobs = []
        for tenant in conn.list_tenants():
            open_alerts = run_tool(conn, tenant, "list_alerts", {"status": "open"})["data"]["alerts"]
            for a in open_alerts[:2]:
                jobs.append((tenant, a["id"]))
        jobs = jobs[:4]

        def run_job(job):
            tenant, alert_id = job
            t0 = time.time()
            try:
                res = investigate_alert(conn, tenant, alert_id)
                out = {
                    "tenant": tenant, "alert_id": alert_id, "seconds": round(time.time() - t0, 1),
                    "handoff": res.handoff, "case_id": res.case_id,
                    "verdict": (res.investigator_final or res.analyst_final or {}).get("verdict"),
                    "tool_calls": len(res.turns),
                }
            except Exception as exc:
                out = {"tenant": tenant, "alert_id": alert_id,
                       "seconds": round(time.time() - t0, 1), "error": str(exc)[:200]}
            return out

        t0 = time.time()
        with ThreadPoolExecutor(max_workers=len(jobs) or 1) as pool:
            results = list(pool.map(run_job, jobs))
        return {"parallelism": len(jobs), "wall_seconds": round(time.time() - t0, 1),
                "results": results}

    @app.get("/")
    def index() -> FileResponse:
        return FileResponse(STATIC_DIR / "console.html")

    # ---- live feed: new synthetic alerts arrive while the console is open ----
    if LIVE_FEED:
        @app.on_event("startup")
        async def start_feed() -> None:  # pragma: no cover
            async def feed_loop():
                while True:
                    await asyncio.sleep(45)
                    try:
                        tenants = conn.list_tenants()
                        if not tenants:
                            continue
                        tenant = tenants[feed_state["counter"] % len(tenants)]
                        feed_state["counter"] += 1
                        code = {"aurora": "AUR", "nimbus": "NMB", "verdant": "VRD"}[tenant]
                        kind, sev, template = FEED_TEMPLATES[feed_state["counter"] % len(FEED_TEMPLATES)]
                        alerts = run_tool(conn, tenant, "list_alerts", {"status": "open"})["data"]["alerts"]
                        target = next((a["account"] for a in alerts), None)
                        if not target:
                            continue
                        alert_id = f"{code}-ALR-{900 + feed_state['counter']:03d}"
                        summary = template.format(acct=target, amt=f"{9_000 + (feed_state['counter'] * 137) % 900:,}",
                                                  n=3 + feed_state["counter"] % 3)
                        conn.write(tenant, "CREATE (x:Alert {id: $id, kind: $kind, severity: $sev, "
                                           "at: $at, amount: $amount, status: 'open', summary: $summary})",
                                   {"id": alert_id, "kind": kind, "sev": sev, "at": _now(),
                                    "amount": 0, "summary": summary})
                        conn.write(tenant, "MATCH (x:Alert {id: $id}), (a:Account {id: $acc}) CREATE (x)-[:ABOUT]->(a)",
                                   {"id": alert_id, "acc": target})
                    except Exception:
                        continue

            asyncio.create_task(feed_loop())

    return app
